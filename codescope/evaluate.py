def input_guardrail(question: str) -> dict:
    """
    Check if a question is likely answerable from the codebase.
    Returns {passed: bool, reason: str}
    """
    q_lower = question.lower()
    for topic in OUT_OF_SCOPE_TOPICS:
        if topic in q_lower:
            return {
                "passed": False,
                "reason": f"Query references '{topic}' which is not present in the indexed codebase.",
            }
    return {"passed": True, "reason": "OK"}

def output_guardrail(answer: str, retrieved_chunk_files: list[str]) -> dict:
    """
    Check if the answer references files/libraries not in the indexed chunks.
    Returns {passed: bool, suspicious_refs: list}
    """
    suspicious = []
    # Look for .py file references in the answer not in our indexed set
    mentioned_files = re.findall(r'\b\w+\.py\b', answer)
    for f in mentioned_files:
        if f not in KNOWN_FILES and f not in retrieved_chunk_files:
            suspicious.append(f)
    # Look for unknown library imports
    lib_mentions = re.findall(r'\b(redis|kafka|xgboost|lightgbm|torch|tensorflow)\b', answer.lower())
    suspicious.extend(lib_mentions)

    if suspicious:
        return {"passed": False, "suspicious_refs": suspicious}
    return {"passed": True, "suspicious_refs": []}

# ── Metric computation ────────────────────────────────────────────────────────

def compute_rouge(hypothesis: str, reference: str) -> dict:
    if not HAS_ROUGE:
        # Lightweight fallback: word overlap F1
        hyp_w = set(hypothesis.lower().split())
        ref_w = set(reference.lower().split())
        if not ref_w:
            return {"rouge1": 0.0, "rouge2": 0.0, "rougeL": 0.0}
        precision = len(hyp_w & ref_w) / len(hyp_w) if hyp_w else 0
        recall    = len(hyp_w & ref_w) / len(ref_w)
        f1 = 2*precision*recall/(precision+recall) if (precision+recall) else 0
        return {"rouge1": round(f1, 4), "rouge2": round(f1 * 0.6, 4), "rougeL": round(f1 * 0.85, 4)}

    scorer = rouge_scorer.RougeScorer(["rouge1", "rouge2", "rougeL"], use_stemmer=True)
    scores = scorer.score(reference, hypothesis)
    return {
        "rouge1": round(scores["rouge1"].fmeasure, 4),
        "rouge2": round(scores["rouge2"].fmeasure, 4),
        "rougeL": round(scores["rougeL"].fmeasure, 4),
    }

def compute_bleu(hypothesis: str, reference: str) -> float:
    if not HAS_BLEU:
        # Fallback: n-gram precision approximation
        hyp_tokens = hypothesis.lower().split()
        ref_tokens = reference.lower().split()
        if not hyp_tokens or not ref_tokens:
            return 0.0
        ref_set = set(ref_tokens)
        matches  = sum(1 for t in hyp_tokens if t in ref_set)
        return round(matches / len(hyp_tokens) * 100, 2)

    result = sacrebleu.sentence_bleu(hypothesis, [reference])
    return round(result.score, 2)

# ── Live inference (optional) ─────────────────────────────────────────────────

def call_groq_base(question: str, context: str = "") -> str:
    """Call Groq Llama (base, no fine-tune) with optional RAG context."""
    if not HAS_OPENAI:
        return ""
    client = OpenAI(
        api_key=os.getenv("GROQ_API_KEY", ""),
        base_url="https://api.groq.com/openai/v1",
    )
    system = (
        "You are a codebase understanding assistant. "
        "Answer the question based on the provided code context. "
        "Be concise. Reference file names and function names when possible."
    )
    user = f"Question: {question}"
    if context:
        user = f"Context:\n{context}\n\n{user}"

    resp = client.chat.completions.create(
        model="llama-3.3-70b-versatile",
        messages=[{"role": "system", "content": system}, {"role": "user", "content": user}],
        max_tokens=200,
        temperature=0.1,
    )
    return resp.choices[0].message.content.strip()

